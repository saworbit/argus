#!/usr/bin/env python3
"""Stamp the QC build identity into src/argus_build.qc (#823).

A tape used to carry no record of the progs.dat that recorded it, so the lab
spine guessed the build from merge times. This tool hashes the QC source that
progs.src lists and writes the hash into a generated QC file holding one
string constant, ARGUS_BUILD. Argus_Init prints it in every match as
`ARGUS build <id>`.

The hash covers the source with comments and layout removed: string and
vector literals are kept byte for byte, every other run of whitespace becomes
one space (or one newline when it held a newline, so preprocessor lines keep
their shape), and comments count as whitespace. A comment-only edit therefore
keeps the stamp, and with it the compiled bytes, which the project relies on
when it proves a comment change inert by comparing binaries.

The stamp file itself is excluded from the hash. It is committed, so the
identity of any commit is `git show <commit>:src/argus_build.qc`, and the CI
check `argus_ci.py stamp` fails when it is stale.

Usage:
  python tools/argus_build_stamp.py            print the current identity
  python tools/argus_build_stamp.py --write    rewrite argus_build.qc if stale
  python tools/argus_build_stamp.py --check    exit 1 when the stamp is stale
  python tools/argus_build_stamp.py --src DIR  stamp another source tree
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STAMP_FILE = "argus_build.qc"
ID_LEN = 12
LINES = re.compile(r"\r\n|\r|\n")
SPACE = " \t\n\r\x0b\x0c"  # explicit, so the Rust twin can match it exactly
STAMP_RE = re.compile(r'^\s*string\s+ARGUS_BUILD\s*=\s*"([0-9a-f]+)"\s*;', re.M)

HEADER = """\
// GENERATED by tools/argus_build_stamp.py - do not edit by hand.
//
// The build identity (#823): a hash of every QC file progs.src lists,
// with comments and layout removed, so a comment-only change keeps both
// this stamp and the compiled bytes. Argus_Init prints it in every match
// as "ARGUS build <id>". The lab's compile and ship steps rewrite it, and
// the CI check argus_ci.py stamp fails while it is stale.
"""


def normalise(text):
    """QC text with comments and layout removed, literals kept verbatim."""
    out = []
    i, n = 0, len(text)
    gap = None  # None, " " or "\n": the separator owed before the next token

    def owe(sep):
        nonlocal gap
        if sep == "\n" or gap is None:
            gap = sep

    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            end = n if j < 0 else j + 2
            owe("\n" if "\n" in text[i:end] else " ")
            i = end
            continue
        if c in SPACE:
            owe("\n" if c == "\n" else " ")
            i += 1
            continue
        if gap is not None:
            if out:
                out.append(gap)
            gap = None
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            j = min(j, n - 1)
            out.append(text[i:j + 1])
            i = j + 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def listed_files(src):
    """progs.src's include list in order, without the stamp file itself."""
    files = []
    inside = False
    for raw in LINES.split((src / "progs.src").read_bytes().decode("latin-1")):
        line = raw.split("//", 1)[0].strip()
        if not line:
            continue
        if line == "#includelist":
            inside = True
            continue
        if line == "#endlist":
            break
        if not inside or line.startswith("#"):
            continue
        if Path(line).name == STAMP_FILE:
            continue
        files.append(line.replace("\\", "/"))
    if not files:
        raise ValueError("%s/progs.src lists no files" % src)
    return files


def compute(src):
    """The build identity of the source tree at src."""
    src = Path(src)
    digest = hashlib.md5()
    for name in ["progs.src", *listed_files(src)]:
        text = (src / name).read_bytes().decode("latin-1")
        if name == "progs.src":
            text = "\n".join(l for l in LINES.split(text)
                             if Path(l.split("//", 1)[0].strip()).name != STAMP_FILE)
        digest.update(name.encode("utf-8") + b"\0")
        digest.update(normalise(text).encode("latin-1") + b"\0")
    return digest.hexdigest()[:ID_LEN]


def read_stamp(src):
    """The identity argus_build.qc currently holds, or None."""
    path = Path(src) / STAMP_FILE
    if not path.is_file():
        return None
    match = STAMP_RE.search(path.read_text(encoding="latin-1"))
    return match[1] if match else None


def render(build_id):
    return HEADER + '\nstring ARGUS_BUILD = "%s";\n' % build_id


def write(src):
    """Rewrite the stamp when it is stale; returns (id, changed)."""
    src = Path(src)
    build_id = compute(src)
    if read_stamp(src) == build_id:
        return build_id, False
    (src / STAMP_FILE).write_bytes(render(build_id).encode("ascii"))
    return build_id, True


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Stamp the QC build identity into src/argus_build.qc (#823).")
    ap.add_argument("--src", default=str(ROOT / "src"),
                    help="QC source tree holding progs.src (default: src/)")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true",
                      help="rewrite argus_build.qc when it is stale")
    mode.add_argument("--check", action="store_true",
                      help="exit 1 when argus_build.qc is missing or stale")
    ap.add_argument("--json", action="store_true", help="print a JSON record")
    args = ap.parse_args(argv)
    src = Path(args.src)
    try:
        if args.write:
            build_id, changed = write(src)
            stamped = build_id
        else:
            build_id, changed = compute(src), False
            stamped = read_stamp(src)
    except (OSError, ValueError) as error:
        print("argus_build_stamp: %s" % error, file=sys.stderr)
        return 2
    current = stamped == build_id
    if args.json:
        print(json.dumps({"build": build_id, "stamped": stamped,
                          "current": current, "rewritten": changed}))
    elif args.write:
        print("%s %s" % (build_id, "written" if changed else "already current"))
    elif args.check:
        if current:
            print("stamp: ok (%s)" % build_id)
        else:
            print("stamp: %s/%s holds %s but the source is %s - run "
                  "python tools/argus_build_stamp.py --write"
                  % (src, STAMP_FILE, stamped or "nothing", build_id))
    else:
        print(build_id)
    return 1 if args.check and not current else 0


if __name__ == "__main__":
    sys.exit(main())

//! The QC build identity (#823), the Rust twin of tools/argus_build_stamp.py.
//!
//! A tape prints `ARGUS build <id>`, where the id hashes every QC file that
//! progs.src lists, with comments and layout removed, so a comment-only edit
//! keeps the stamp and the compiled bytes. The compile step refreshes the
//! generated `argus_build.qc` before fteqcc runs, so a binary always names the
//! source it was built from. The Python tool is the reference: a test below
//! holds this module to the stamp the repository commits.

use std::path::Path;

pub const STAMP_FILE: &str = "argus_build.qc";
pub const ID_LEN: usize = 12;

const HEADER: &str = "\
// GENERATED by tools/argus_build_stamp.py - do not edit by hand.
//
// The build identity (#823): a hash of every QC file progs.src lists,
// with comments and layout removed, so a comment-only change keeps both
// this stamp and the compiled bytes. Argus_Init prints it in every match
// as \"ARGUS build <id>\". The lab's compile and ship steps rewrite it, and
// the CI check argus_ci.py stamp fails while it is stale.
";

/// QC text with comments and layout removed and literals kept verbatim.
/// Mirrors `normalise` in tools/argus_build_stamp.py byte for byte.
pub fn normalise(text: &[u8]) -> Vec<u8> {
    let n = text.len();
    let mut out = Vec::with_capacity(n);
    let mut gap: Option<u8> = None;
    let owe = |gap: &mut Option<u8>, sep: u8| {
        if sep == b'\n' || gap.is_none() {
            *gap = Some(sep);
        }
    };
    let mut i = 0;
    while i < n {
        let c = text[i];
        if c == b'/' && i + 1 < n && text[i + 1] == b'/' {
            i = text[i..]
                .iter()
                .position(|&b| b == b'\n')
                .map_or(n, |p| i + p);
            continue;
        }
        if c == b'/' && i + 1 < n && text[i + 1] == b'*' {
            let end = text[i + 2..]
                .windows(2)
                .position(|w| w == b"*/")
                .map_or(n, |p| i + 2 + p + 2);
            let sep = if text[i..end].contains(&b'\n') {
                b'\n'
            } else {
                b' '
            };
            owe(&mut gap, sep);
            i = end;
            continue;
        }
        if c.is_ascii_whitespace() || c == 0x0b {
            owe(&mut gap, if c == b'\n' { b'\n' } else { b' ' });
            i += 1;
            continue;
        }
        if let Some(sep) = gap.take() {
            if !out.is_empty() {
                out.push(sep);
            }
        }
        if c == b'"' || c == b'\'' {
            let mut j = i + 1;
            while j < n && text[j] != c && text[j] != b'\n' {
                j += if text[j] == b'\\' { 2 } else { 1 };
            }
            let j = j.min(n - 1);
            out.extend_from_slice(&text[i..=j]);
            i = j + 1;
            continue;
        }
        out.push(c);
        i += 1;
    }
    out
}

fn is_stamp_line(line: &str) -> bool {
    let code = line.split("//").next().unwrap_or("").trim();
    Path::new(code).file_name().and_then(|n| n.to_str()) == Some(STAMP_FILE)
}

fn listed(progs: &str) -> Vec<String> {
    let mut files = Vec::new();
    let mut inside = false;
    for raw in progs.lines() {
        let line = raw.split("//").next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        if line == "#includelist" {
            inside = true;
            continue;
        }
        if line == "#endlist" {
            break;
        }
        if !inside || line.starts_with('#') || is_stamp_line(line) {
            continue;
        }
        files.push(line.replace('\\', "/"));
    }
    files
}

/// Whether progs.src lists the stamp file, i.e. the tree opts in to stamping.
pub fn opted_in(src: &Path) -> bool {
    std::fs::read(src.join("progs.src"))
        .map(|b| latin1(&b).lines().any(is_stamp_line))
        .unwrap_or(false)
}

fn latin1(bytes: &[u8]) -> String {
    bytes.iter().map(|&b| b as char).collect()
}

/// Python's `str.splitlines` for the line terminators QC source can carry.
fn split_lines(text: &str) -> Vec<&str> {
    let mut lines = Vec::new();
    let mut start = 0;
    let bytes = text.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        match bytes[i] {
            b'\n' => {
                lines.push(&text[start..i]);
                start = i + 1;
            }
            b'\r' => {
                lines.push(&text[start..i]);
                if i + 1 < bytes.len() && bytes[i + 1] == b'\n' {
                    i += 1;
                }
                start = i + 1;
            }
            _ => {}
        }
        i += 1;
    }
    if start < text.len() {
        lines.push(&text[start..]);
    }
    lines
}

/// The build identity of the source tree at `src`.
pub fn compute(src: &Path) -> Result<String, String> {
    let progs_path = src.join("progs.src");
    let progs = std::fs::read(&progs_path).map_err(|e| format!("{}: {e}", progs_path.display()))?;
    let progs = latin1(&progs);
    let files = listed(&progs);
    if files.is_empty() {
        return Err(format!("{} lists no files", progs_path.display()));
    }
    let mut ctx = md5::Context::new();
    let kept: Vec<&str> = split_lines(&progs)
        .into_iter()
        .filter(|l| !is_stamp_line(l))
        .collect();
    ctx.consume(b"progs.src\0");
    ctx.consume(normalise(&latin1_bytes(&kept.join("\n"))));
    ctx.consume(b"\0");
    for name in files {
        let path = src.join(&name);
        let bytes = std::fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        ctx.consume(name.as_bytes());
        ctx.consume(b"\0");
        ctx.consume(normalise(&bytes));
        ctx.consume(b"\0");
    }
    let hex = format!("{:x}", ctx.finalize());
    Ok(hex[..ID_LEN].to_string())
}

fn latin1_bytes(text: &str) -> Vec<u8> {
    text.chars().map(|c| c as u32 as u8).collect()
}

/// The identity argus_build.qc currently holds, if any.
pub fn read_stamp(src: &Path) -> Option<String> {
    let text = std::fs::read_to_string(src.join(STAMP_FILE)).ok()?;
    let re = regex::Regex::new(r#"(?m)^\s*string\s+ARGUS_BUILD\s*=\s*"([0-9a-f]+)"\s*;"#).ok()?;
    re.captures(&text).map(|c| c[1].to_string())
}

pub fn render(id: &str) -> String {
    format!("{HEADER}\nstring ARGUS_BUILD = \"{id}\";\n")
}

/// Refresh the stamp before a compile. `Ok(None)` when the tree does not list
/// the stamp file (an older tree or a fixture copy that predates #823).
pub fn refresh(src: &Path) -> Result<Option<String>, String> {
    if !opted_in(src) {
        return Ok(None);
    }
    let id = compute(src)?;
    if read_stamp(src).as_deref() != Some(id.as_str()) {
        let path = src.join(STAMP_FILE);
        std::fs::write(&path, render(&id)).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(Some(id))
}

#[cfg(test)]
mod tests {
    use super::*;

    const PROGS: &str = "#pragma progs_dat \"../lq1/progs.dat\"\n#includelist\ndefs.qc\nargus_build.qc          // generated\nargus.qc   // the bot\n#endlist\n";
    const ARGUS: &str =
        "void() f =\n{\n    dprint (\"a  b // not a comment\\n\");\n    x = 1;\n};\n";

    fn tree(dir: &Path, argus: &str) {
        std::fs::create_dir_all(dir).unwrap();
        std::fs::write(dir.join("progs.src"), PROGS).unwrap();
        std::fs::write(dir.join("defs.qc"), "float x;\n").unwrap();
        std::fs::write(dir.join("argus.qc"), argus).unwrap();
    }

    fn scratch(tag: &str) -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!("argus-stamp-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        dir
    }

    #[test]
    fn normalise_matches_the_shared_cases() {
        #[derive(serde::Deserialize)]
        struct Case {
            name: String,
            source: String,
            expected: String,
        }
        let cases: Vec<Case> =
            serde_json::from_str(include_str!("../testdata/build_normalise_cases.json")).unwrap();
        let bytes = |text: &str| {
            text.chars()
                .map(|c| u8::try_from(c as u32).unwrap())
                .collect::<Vec<_>>()
        };
        for case in cases {
            assert_eq!(
                normalise(&bytes(&case.source)),
                bytes(&case.expected),
                "{}",
                case.name
            );
        }
    }

    #[test]
    fn comment_only_change_keeps_identity_and_code_change_moves_it() {
        let a = scratch("a");
        let b = scratch("b");
        let c = scratch("c");
        tree(&a, ARGUS);
        tree(
            &b,
            &format!("// header\n{}", ARGUS.replace("x = 1;", "x = 1; /* set */")),
        );
        tree(&c, &ARGUS.replace("1;", "2;"));
        let ia = compute(&a).unwrap();
        assert_eq!(ia.len(), ID_LEN);
        assert_eq!(ia, compute(&b).unwrap());
        assert_ne!(ia, compute(&c).unwrap());
        for d in [a, b, c] {
            let _ = std::fs::remove_dir_all(d);
        }
    }

    #[test]
    fn refresh_writes_once_and_skips_trees_that_do_not_opt_in() {
        let a = scratch("refresh");
        tree(&a, ARGUS);
        let id = refresh(&a).unwrap().expect("opted in");
        assert_eq!(read_stamp(&a).as_deref(), Some(id.as_str()));
        let before = std::fs::metadata(a.join(STAMP_FILE))
            .unwrap()
            .modified()
            .unwrap();
        assert_eq!(refresh(&a).unwrap().as_deref(), Some(id.as_str()));
        let after = std::fs::metadata(a.join(STAMP_FILE))
            .unwrap()
            .modified()
            .unwrap();
        assert_eq!(before, after, "an unchanged stamp is not rewritten");
        std::fs::write(
            a.join("progs.src"),
            PROGS.replace("argus_build.qc          // generated\n", ""),
        )
        .unwrap();
        assert_eq!(refresh(&a).unwrap(), None);
        let _ = std::fs::remove_dir_all(a);
    }

    /// The repository commits the stamp the Python reference wrote, and CI
    /// keeps it current; this module must arrive at the same identity.
    #[test]
    fn agrees_with_the_committed_python_stamp() {
        let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src");
        if !opted_in(&src) {
            return;
        }
        assert_eq!(compute(&src).ok(), read_stamp(&src));
    }
}
